#!/usr/bin/env python3
"""Compile the SDK helper and embed it into one Android SH. Python standard library only."""
import argparse
import base64
import gzip
import hashlib
import io
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import zipfile

ROOT = Path(__file__).resolve().parent
VERSION = '1.0.0'


def find_ndk(value):
    if value:
        return Path(value).expanduser().resolve()
    for name in ('ANDROID_NDK_HOME', 'ANDROID_NDK_ROOT', 'NDK_ROOT'):
        if os.environ.get(name):
            return Path(os.environ[name]).expanduser().resolve()
    for name in ('ANDROID_SDK_ROOT', 'ANDROID_HOME'):
        if os.environ.get(name):
            candidates = list((Path(os.environ[name]) / 'ndk').glob('*/source.properties'))
            if candidates:
                def version(path):
                    return tuple(int(v) for v in path.parent.name.split('.') if v.isdigit())
                return max(candidates, key=version).parent.resolve()
    raise SystemExit('NDK not found. Use --ndk PATH or set ANDROID_NDK_HOME.')


def payload_bytes(helper):
    stream = io.BytesIO()
    with tarfile.open(fileobj=stream, mode='w', format=tarfile.USTAR_FORMAT) as archive:
        for name, data in [('main.sh', (ROOT / 'module_force_clean.template.sh').read_bytes().replace(b'\r\n', b'\n')),
                           ('skp_module_query', helper.read_bytes())]:
            member = tarfile.TarInfo(name)
            member.size = len(data)
            member.mode = 0o700
            member.mtime = 0
            member.uid = member.gid = 0
            archive.addfile(member, io.BytesIO(data))
    return gzip.compress(stream.getvalue(), compresslevel=9, mtime=0)


def pack(helper, output):
    data = helper.read_bytes()
    if data[:4] != b'\x7fELF' or data[4:6] != b'\x02\x01' or int.from_bytes(data[18:20], 'little') != 183:
        raise SystemExit('Helper must be a little-endian AArch64 ELF64 executable.')
    payload = payload_bytes(helper)
    digest = hashlib.sha256(payload).hexdigest()
    stub = r'''#!/system/bin/sh
# SKP模块强制清理 ❤ Github/CedarXuesong
# Generated by build.py. Contains the SDK-linked AArch64 helper, never a device key.
set -eu
umask 077
case "${1:-}" in
    --version) echo '@VERSION@'; exit 0 ;;
    --help|-h)
        printf '%s\n' 'SKP模块强制清理 ❤ Github/CedarXuesong' \
          "用法：su -c 'sh SKRootPro-module-force-clean.sh'" \
          '默认隐藏输入 SKP 密钥并自动定位模块目录。' \
          '参数：--id ID [--apply] [--reboot] [--module-root /data/NAME/modules]' \
          '      [--legacy-id ID] [--color|--no-color] [--version]'
        exit 0 ;;
esac
[ "$(id -u)" = 0 ] || { echo '请通过 su 运行本脚本。' >&2; exit 1; }
case "$(uname -m)" in aarch64|arm64) ;; *) echo '当前版本需要 AArch64 Android。' >&2; exit 1 ;; esac
for cmd in readlink awk base64 tar sha256sum; do
    command -v "$cmd" >/dev/null 2>&1 || { echo "缺少命令：$cmd" >&2; exit 1; }
done
[ "$(readlink -f /data/local/tmp)" = /data/local/tmp ] || exit 1
runtime_dir="/data/local/tmp/skp-force-clean-runtime-$(date +%Y%m%d_%H%M%S)-$$"
mkdir -m 700 "$runtime_dir"
[ "$(readlink -f "$runtime_dir")" = "$runtime_dir" ] || exit 1
cleanup() {
    if [ ! -L "$runtime_dir" ] && [ "$(readlink -f "$runtime_dir")" = "$runtime_dir" ]; then
        rm -f -- "$runtime_dir/main.sh" "$runtime_dir/skp_module_query" "$runtime_dir/payload.tar.gz"
        rmdir "$runtime_dir" 2>/dev/null || :
    fi
}
trap cleanup 0
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP
awk 'seen {print} /^__SKP_PAYLOAD_BELOW__$/ {seen=1}' "$0" | base64 -d > "$runtime_dir/payload.tar.gz"
actual=$(sha256sum "$runtime_dir/payload.tar.gz")
actual=${actual%% *}
[ "$actual" = '@PAYLOAD_SHA256@' ] || { echo '内置载荷校验失败，停止执行。' >&2; exit 1; }
tar -xzf "$runtime_dir/payload.tar.gz" -C "$runtime_dir"
chmod 700 "$runtime_dir/main.sh" "$runtime_dir/skp_module_query"
status=0
SKP_HELPER="$runtime_dir/skp_module_query" sh "$runtime_dir/main.sh" "$@" || status=$?
exit "$status"
__SKP_PAYLOAD_BELOW__
'''.replace('@VERSION@', VERSION).replace('@PAYLOAD_SHA256@', digest)
    output.write_bytes(stub.encode('utf8') + base64.encodebytes(payload))
    output.chmod(0o755)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ndk', help='Android NDK root (auto-detected from environment otherwise)')
    parser.add_argument('--sdk', default=os.environ.get('SKP_SDK_ROOT'), help='Reference kernel_module_kit directory')
    parser.add_argument('--helper', type=Path, help='Package an already compiled helper; skips NDK/SDK lookup')
    parser.add_argument('--out', type=Path, default=ROOT / 'dist')
    args = parser.parse_args()
    args.out = args.out.resolve()
    args.out.mkdir(parents=True, exist_ok=True)
    helper = args.out / 'skp_module_query'
    if args.helper:
        if args.helper.resolve() != helper:
            shutil.copyfile(args.helper, helper)
    else:
        if not args.sdk:
            parser.error('Specify --sdk /path/to/kernel_module_kit or set SKP_SDK_ROOT.')
        sdk = Path(args.sdk).expanduser().resolve()
        if not (sdk / 'lib/libkernel_module_kit_static.a').is_file():
            parser.error('SDK static library not found under --sdk directory.')
        ndk = find_ndk(args.ndk)
        host = {'win32': 'windows-x86_64', 'linux': 'linux-x86_64', 'darwin': 'darwin-x86_64'}.get(sys.platform)
        if not host:
            parser.error('Unsupported build host.')
        clang = ndk / 'toolchains/llvm/prebuilt' / host / 'bin' / ('clang++.exe' if sys.platform == 'win32' else 'clang++')
        command = [str(clang), '--target=aarch64-linux-android29', '-std=c++20', '-O2', '-Wall', '-Wextra', '-Werror',
                   '-fno-emulated-tls', '-fPIE', '-pie', '-static-libstdc++', '-Wl,-z,relro,-z,now,-s',
                   '-isystem', str(sdk / 'include'), str(ROOT / 'skp_module_query.cpp'),
                   str(sdk / 'lib/libkernel_module_kit_static.a'), '-lz', '-ldl', '-llog', '-o', str(helper)]
        subprocess.run(command, check=True)
    script = args.out / 'SKRootPro-module-force-clean.sh'
    pack(helper, script)
    checksums = hashlib.sha256(script.read_bytes()).hexdigest() + '  ' + script.name + '\n'
    (args.out / 'SHA256SUMS.txt').write_bytes(checksums.encode('ascii'))
    (args.out / 'helper-SHA256SUMS.txt').write_bytes((hashlib.sha256(helper.read_bytes()).hexdigest() + '  ' + helper.name + '\n').encode('ascii'))
    bundle = args.out / ('SKRootPro-module-force-clean-v' + VERSION + '.zip')
    with zipfile.ZipFile(bundle, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in (script, args.out / 'SHA256SUMS.txt', ROOT / 'README.md', ROOT / 'THIRD_PARTY_NOTICES.md'):
            if path.is_file():
                archive.write(path, path.name)
    print('Built:', script)
    print('SHA256:', hashlib.sha256(script.read_bytes()).hexdigest())
    print('Single-file release size:', script.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
